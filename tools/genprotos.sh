#!/bin/sh
# Regenerates csrc/protos.h: prototypes for every function defined in the game's C files.
# gcc -aux-info lists the prototype of each function (converted from K&R definitions).
# Run from the repo root:  tools/genprotos.sh
set -e
cd "$(dirname "$0")/../csrc"
: > protos.tmp
for f in fmain fmain2 iffsubs hdrive; do
	gcc -std=gnu89 -fsyntax-only -w -I. -Istubs -DNO_PROTOS -aux-info $f.aux $f.c 2>/dev/null || true
	# keep only definitions from this file ("/* fmain.c:123:NC */" or ":OC" for old-style)
	grep -E "^/\* $f\.c:[0-9]+:[NO][CF] \*/" $f.aux | sed -E "s|^/\* [^*]*\*/ ||; s/register //g; s| /\* .*\*/$||" >> protos.tmp
	rm -f $f.aux
done
{
	echo '/* protos.h - generated by tools/genprotos.sh, do not edit */'
	echo 'struct sshape; struct encounter; struct extent; struct object; struct need;'
	sort -u protos.tmp
} > protos.h
rm -f protos.tmp
